const fs = require("fs");
const path = require("path");

const dir = path.join(
  __dirname,
  "assets",
  "pokemon_images",
  "chaos_rising",
  "large",
);
const files = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith(".png"))
  .sort((a, b) => parseInt(a) - parseInt(b));

const lines = files.map(
  (f) =>
    `  ${parseInt(f)}: require("../assets/pokemon_images/chaos_rising/large/${f}"),`,
);

const outDir = path.join(__dirname, "constants");
fs.mkdirSync(outDir, { recursive: true });

fs.writeFileSync(
  path.join(outDir, "pokemonLargeImages.ts"),
  `// AUTO-GENERATED by generateImages.js\nconst pokemonImages: Record<number, any> = {\n${lines.join("\n")}\n};\nexport default pokemonImages;\n`,
);
console.log(`Wrote ${files.length} entries`);
